def expose_sessions(case: dict, base: float) -> list[dict]:
    """case + 运行锚 base → 按时间升序的暴露轮 session 列表。

    每条学生问句的时间严格取 entry_observations 推导的期望观测时刻（第 k 次
    出现的 topic ↔ levels[k]）；同一时刻的问句合并进同一 session（一 session
    多轮 = 一段对话里连着问），session 之间时间不同 → consolidate 各切一段、
    各写一条观测。返回 [{at, turns: [{topic_id, q}]}]。

    自检：剧本总轮数 ≠ 期望档数时 ValueError（案例与剧本打架，先修数据再跑）。
    """
    turns = SCRIPTS[case["id"]]
    obs_times: dict[str, list[float]] = {}
    for m in case["mastery"]:
        obs_times[m["topic_id"]] = [
            o["created_at"] for o in entry_observations(case, m, base=base)
        ]
    expected = sum(len(v) for v in obs_times.values())
    if len(turns) != expected:
        raise ValueError(
            f"[{case['id']}] 剧本 {len(turns)} 轮 ≠ 期望观测 {expected} 档——剧本与案例打架"
        )
    seen: dict[str, int] = {}
    entries: list[tuple[float, int, str, str]] = []  # (at, script_idx, topic, q)
    for idx, (tid, q) in enumerate(turns):
        j = seen.get(tid, 0)
        seen[tid] = j + 1
        if j >= len(obs_times.get(tid, [])):
            raise ValueError(f"[{case['id']}] 剧本里 {tid} 出现次数超过期望档数")
        entries.append((obs_times[tid][j], idx, tid, q))
    sessions: list[dict] = []
    for at, _idx, tid, q in sorted(entries, key=lambda x: (x[0], x[1])):
        if not sessions or sessions[-1]["at"] != at:
            sessions.append({"at": at, "turns": []})
        sessions[-1]["turns"].append({"topic_id": tid, "q": q})
    return sessions


